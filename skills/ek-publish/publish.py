#!/usr/bin/env python3
"""
ek-publish — build both portals of a project, lock them as the manifest says, place them for the host, and write
the private project README with the two links.

  python -X utf8 skills/ek-publish/publish.py --manifest project.config.json --brief work/brief.json \
         [--root .] [--out-dir <folder>] [--run-gh]

Reads the manifest's `publish` block:
  { "host": "github-pages" | "own",
    "repo": "owner/name",              (github-pages)
    "pages_dir": "docs",               (github-pages; the folder Pages serves from on main; letters, digits, - and _)
    "domain": "https://example.org/engage",   (own)
    "user_portal":  {"lock": false, "path": "", "title": "Engagement tool"},
    "admin_portal": {"lock": true,  "path": ""},
    "passphrases_dir": "<folder outside the repo; relative = relative to the manifest's folder>",
    "public_readme": false }           (true: a minimal README in the pages folder, user link only)

Steps: user portal = chain.py (portal user); admin portal = chain.py --portal admin; each locked portal is encrypted
with ek-lock-page/lock.py under its own passphrase file (user.txt / admin.txt in passphrases_dir, generated by lock.py
when missing, except after a recorded publish: then a missing file stops the run); an empty path gets a random hex
path, written back to the manifest; pages go to <pages_dir>/p/<path>/index.html (github-pages) or
dist/<path>/index.html (own). The full README goes to output/README.md (private, never published); nothing is written
into the pages folder besides the pages unless publish.public_readme is true. After success each portal block gets
"published": true and "published_on". For github-pages a beginner route and the gh commands are printed; --run-gh
runs the gh commands only from an interactive terminal after the person types the repository name (agents never pass
it). This script never commits or pushes. It never reads, holds or prints a passphrase or an API key.

--out-dir puts everything this script writes (plain builds, README, pages_dir, dist) under one folder, for a trial
run that must not touch the repo; the manifest is still updated (paths, published).
"""
from __future__ import annotations

import argparse
import datetime
import json
import re
import secrets
import shutil
import subprocess
import sys
from pathlib import Path

KIT = Path(__file__).resolve().parent.parent.parent
CHAIN = KIT / "skills" / "ek-shell" / "chain.py"
LOCK = KIT / "skills" / "ek-lock-page" / "lock.py"
# 8 hex characters at least; paths generated by earlier versions (16 hex) stay valid
HEXPATH = re.compile(r"^[0-9a-f]{8,64}$")
PAGES_DIR = re.compile(r"^[A-Za-z0-9_-]{1,40}$")
SECRETISH = re.compile(r"(api[_-]?key|^key$|secret|token|password|passphrase$)", re.I)
REPO = re.compile(r"^[A-Za-z0-9-]{1,39}/[A-Za-z0-9._-]{1,100}$")
TEMP_GLOB = ".ek-admin-manifest-*.json"
PRIVATE_LINE = "**Private: keep this file out of any public repository.**"


def fail(msg: str) -> int:
    print(f"[publish] {msg}", file=sys.stderr)
    return 2


def secret_fields(block, where: str) -> list[str]:
    """Names (never values) of fields that look like they hold a key; a key must not be in the manifest."""
    found = []
    if isinstance(block, dict):
        for k, v in block.items():
            if SECRETISH.search(str(k)) and k != "passphrases_dir" and v not in (None, "", False):
                found.append(f"{where}.{k}")
            found += secret_fields(v, f"{where}.{k}")
    return found


def inside(child: Path, parent: Path) -> bool:
    try:
        child.resolve().relative_to(parent.resolve())
        return True
    except ValueError:
        return False


def run(cmd: list[str]) -> tuple[int, str]:
    r = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    return r.returncode, ((r.stdout or "") + (r.stderr or "")).strip()


def pages_url(repo: str, path: str) -> str:
    owner, name = repo.split("/", 1)
    base = f"https://{owner.lower()}.github.io" + ("" if name.lower() == f"{owner.lower()}.github.io" else f"/{name}")
    return f"{base}/p/{path}/"


def kv_lines(block: dict, skip=("lock_key",)) -> list[str]:
    out = []
    for k, v in (block or {}).items():
        if k in skip or SECRETISH.search(str(k)):
            continue
        if isinstance(v, (dict, list)):
            v = json.dumps(v, ensure_ascii=False)
        out.append(f"- **{k}**: {v}")
    return out


def beginner_route(repo: str, pages_dir: str, links: dict, local_pages: Path) -> list[str]:
    """GitHub Pages without a command line, for someone who has never used GitHub."""
    owner, name = repo.split("/", 1)
    return [
        f"1. Create a GitHub account at https://github.com/signup (free).",
        f"2. If the tool is for a closed group, create a free organisation for this project: your picture (top right) →"
        f" Your organizations → New organization → Free, named `{owner}`. Its pages get their own web address"
        f" ({owner.lower()}.github.io), which keeps this group's data apart from any other pages you publish.",
        f"3. Create a repository in it: + (top right) → New repository → owner `{owner}`, name `{name}`, Public (free"
        f" Pages needs a public repository; a locked portal is stored only as ciphertext) → Create repository.",
        f"4. Upload the pages folder: in the new repository, Add file → Upload files, and drag in the whole"
        f" `{pages_dir}` folder from {local_pages.parent} (the folder itself, so the repository shows `{pages_dir}/`)."
        f" Commit changes. (GitHub Desktop works too: clone the repository, copy `{pages_dir}` into it, commit, push.)"
        f" Upload nothing else: never the plain builds, the README next to them, or the passphrase files.",
        f"5. Settings → Pages → Build and deployment: Source \"Deploy from a branch\", branch `main`, folder"
        f" `/{pages_dir}` → Save.",
        f"6. Wait a minute or two (the Actions tab shows the build), then open the two links:",
        f"   user portal  {links['user']}",
        f"   admin portal {links['admin']}",
        f"   After a rebuild, upload the `{pages_dir}` folder again the same way (it replaces the old files).",
    ]


def gh_commands(repo: str, pages_dir: str) -> list[str]:
    return [
        f"# for people who use a terminal; the beginner route above does the same in the browser",
        f"gh repo create {repo} --public --description \"Engagement tool\"",
        f"# commit and push ONLY the {pages_dir}/ folder to main yourself (never output/, the plain builds,",
        f"# the private README or the passphrase files), then serve Pages from /{pages_dir} on main:",
        f"gh api -X POST repos/{repo}/pages -f \"source[branch]=main\" -f \"source[path]=/{pages_dir}\"",
        f"gh api repos/{repo}/pages --jq .html_url",
    ]


def public_readme(title: str, user_link: str, user_locked: bool) -> str:
    L = [f"# {title}", "", user_link, ""]
    if user_locked:
        L += ["Ask the design team for the passphrase.", ""]
    return "\n".join(L)


def private_readme(m: dict, pub: dict, links: dict, locks: dict, pass_dir: Path | None, rebuild_cmd: str,
                   route: list[str], gh_lines: list[str], upload: str | None) -> str:
    name = str((m.get("project") or {}).get("name") or "Engagement tool")
    host = pub["host"]
    chat = m.get("chat") or {}
    L = [PRIVATE_LINE, "",
         f"# {name}", "", "An engagement tool built with Engage Kit. It has two portals, each its own page.", "",
         "## Links", "",
         f"- **User portal** ({'passphrase' if locks['user'] else 'public, no passphrase'}): {links['user']}",
         f"- **Admin portal** ({'passphrase' if locks['admin'] else 'public, no passphrase'}): {links['admin']}", ""]
    if host == "own":
        L += [f"These links assume the contents of the upload folder are served at `{pub.get('domain')}`.", ""]
    L += ["The admin portal does not have to be hosted at all: the design team can open the plain admin build"
          " (`admin/index.html` next to this file) from their own computer, which keeps it entirely off the internet.", ""]
    L += ["## The two portals", "",
          "- **User portal**: for the community and stakeholders. They explore the project, react to it, and the"
          " assistant (if chat is set up for visitors) answers their questions from the team's material."
          " Reactions stay on each visitor's phone until they export them.",
          "- **Admin portal**: for the design team. Everything the user portal has plus an **Admin** section:"
          " load the exports collected from phones, read the merged record, and ask the assistant to analyse the"
          " reactions. Keep this link and its passphrase inside the team.", "",
          "## Passphrases", ""]
    if not (locks["user"] or locks["admin"]):
        L += ["Neither portal is locked.", ""]
    else:
        files = [f"`{p}.txt`" for p in ("user", "admin") if locks[p]]
        L += [f"Each locked portal has its own passphrase, in `{pass_dir}`: {' and '.join(files)} (the first line of the"
              " file). This README never contains a passphrase.", "",
              "How to hand them out:",
              "- Give the passphrase through a different channel from the link (say it at the session, a text message, the"
              " team's password manager), never in the same email or post."]
        if locks["admin"]:
            L += ["- The admin passphrase goes only to the design team."]
        if locks["user"]:
            L += ["- The user passphrase goes to the group invited to react."]
        L += ["- A passphrase can be passed on and nothing records who opened the page.",
              "- Visitors type it each time: the gate does not offer \"remember on this phone\" on a shared origin.", ""]
    L += ["## Rebuild and re-lock", "", "After any change to the brief, the manifest or a skill, from the kit folder:", "",
          "```", rebuild_cmd, "```", "",
          "This rebuilds both portals, re-encrypts each locked one with the passphrase already in its file (same links,"
          " same passphrases) and rewrites this README. Then publish the changed pages"
          + (" (upload the pages folder again, or commit and push it)." if host == "github-pages" else " (upload the folder again)."),
          "",
          "To change a passphrase (revoke): delete its `.txt` file and set `\"published\": false` on that portal in the"
          " manifest, re-run, publish, and tell the group. The script refuses to issue a new passphrase while the manifest"
          " records an earlier publish, so a mistyped folder can never silently lock out a group. Earlier published"
          " versions stay in the host's history and still open with the old passphrase.", ""]
    L += ["## Chat (the assistant)", ""]
    mode = chat.get("mode")
    if not chat or mode in (None, "", "none"):
        L += ["Chat is not set up. To add it, see `skills/ek-project-manifest/SKILL.md` (step 0 and the chat question)"
              " and `skills/ek-chat/PROXY.md`.", ""]
    else:
        L += [f"Mode: **{mode}**. Setup: `skills/ek-chat/PROXY.md`."]
        if mode == "proxy":
            L += ["The LLM key lives only in the proxy (a Cloudflare Worker deployed from `skills/ek-chat/worker.js`). The"
                  " pages only know the proxy's address. The Worker's per-day cap is rough unless its KV namespace"
                  " (`EK_CAP`) is bound; what bounds cost is the monthly spending limit on the Anthropic account.", ""]
        elif mode == "direct":
            L += ["Direct mode: a team member pastes their own key into the admin portal on their own device; it is kept in"
                  " that browser only. The user portal has no chat in this mode.", ""]
        L += ["A key never goes into the manifest, the repository or this README.", ""]
    L += ["## What the host sees", ""]
    hostname = "GitHub (Pages) and its CDN" if host == "github-pages" else "your web host"
    L += [f"- {hostname} {'see' if host == 'github-pages' else 'sees'} each visit: the time, the visitor's IP address and the page requested.",
          "- For a locked portal the host stores and serves only ciphertext; it never sees the content, the passphrase or"
          " the reactions. For a public portal the host serves the page in the clear.",
          "- Reactions stay in each visitor's browser until they export them; nothing is sent to the host.",
          "- The 3D library and fonts load from public CDNs (cdnjs, Google Fonts), which see the visitor's IP.",
          "- If chat is set up, questions go to the proxy and the LLM provider, which see the question text."]
    if host == "github-pages":
        L += ["- A public GitHub repository shows the `p/` folders, so the links are not secret; the passphrase is what"
              " protects a locked portal. Every published version stays in the repository's history."]
    L += [""]
    notes = kv_lines(m.get("hosting") or {}) + kv_lines(m.get("data") or {})
    L += ["## Data notes", ""] + (notes or ["- None recorded in the manifest (`hosting` and `data` blocks). Record the retention period,"
                                         " consent copy and who may see exports before going live."]) + [""]
    if host == "github-pages":
        L += ["## Hosting on GitHub Pages (no command line)", ""] + route + ["", "With a terminal instead:", "", "```"] + gh_lines + ["```", ""]
    if host == "own" and upload:
        L += ["## Hosting on your own site", "",
              f"Upload the contents of `{upload}` to the web folder that `{pub.get('domain')}` points to.",
              "Any static host works as long as it serves HTTPS: the microphone (voice reactions) and the decryption of a"
              " locked portal both need HTTPS.", ""]
    return "\n".join(L)


def interactive() -> bool:
    """A person at a terminal. On Windows the NUL device reports isatty() True, so also ask the console."""
    try:
        if not (sys.stdin and sys.stdin.isatty() and sys.stdout.isatty()):
            return False
        if sys.platform == "win32":
            import ctypes
            import msvcrt
            mode = ctypes.c_uint32()
            return bool(ctypes.windll.kernel32.GetConsoleMode(msvcrt.get_osfhandle(sys.stdin.fileno()), ctypes.byref(mode)))
        return True
    except Exception:
        return False


def confirm_gh(repo: str, pages_dir: str) -> bool:
    print("[publish] --run-gh will, with the GitHub account `gh` is logged into:")
    print(f"   1. create the repository {repo}, PUBLIC (anyone can read it and its history)")
    print(f"   2. turn on GitHub Pages for it, from branch main, folder /{pages_dir}")
    print("   It does not commit, push or upload anything.")
    try:
        typed = input(f"Type the repository name ({repo}) to confirm, anything else to cancel: ").strip()
    except EOFError:
        typed = ""
    return typed == repo


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", type=Path, required=True)
    ap.add_argument("--brief", type=Path, default=None, help="default: the manifest's source.ingested, else work/brief.json (relative to --root)")
    ap.add_argument("--root", type=Path, default=Path("."))
    ap.add_argument("--out-dir", type=Path, default=None, help="write everything under this folder instead of output/, <pages_dir>/ and dist/")
    ap.add_argument("--run-gh", action="store_true",
                    help="github-pages: run the gh commands after a typed confirmation in an interactive terminal (a person only; agents never pass it)")
    args = ap.parse_args(argv)
    mpath = args.manifest.resolve()
    if not mpath.is_file():
        return fail(f"no manifest at {mpath}")
    before = set(mpath.parent.glob(TEMP_GLOB))
    try:
        return publish(args, mpath)
    finally:
        # chain.py removes its temporary manifest in its own finally; this catches one left by a killed build
        for t in set(mpath.parent.glob(TEMP_GLOB)) - before:
            try:
                t.unlink()
                print(f"[publish] removed a leftover temporary manifest {t.name}")
            except OSError:
                pass


def publish(args, mpath: Path) -> int:
    root = args.root.resolve()
    m = json.loads(mpath.read_text(encoding="utf-8-sig"))
    if mpath.read_bytes()[:3] == b"\xef\xbb\xbf":
        # the shell and lock.py read plain UTF-8; a BOM (PowerShell's Out-File adds one) would stop them
        mpath.write_text(json.dumps(m, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print("[publish] removed a UTF-8 byte-order mark from the manifest (the build scripts read plain UTF-8)")
    pub = m.get("publish")
    if not isinstance(pub, dict):
        return fail("the manifest has no 'publish' block; ask the kickoff questions (ek-project-manifest step 5) first")
    bad = secret_fields(m.get("chat"), "chat") + secret_fields(pub, "publish")
    if bad:
        return fail("the manifest holds what looks like a key in " + ", ".join(bad) + "; remove it (a key belongs in the proxy or the"
                    " admin's own browser, never in the manifest) and re-run")
    host = pub.get("host")
    if host not in ("github-pages", "own"):
        return fail("publish.host must be 'github-pages' or 'own'")
    if host == "github-pages" and not REPO.match(str(pub.get("repo") or "")):
        return fail("publish.repo must be 'owner/name' for github-pages")
    if host == "own" and not re.match(r"^https://[^\s/]+", str(pub.get("domain") or "")):
        return fail("publish.domain must be an https:// address for an own host (the microphone and decryption need HTTPS)")
    pages_dir_name = str(pub.get("pages_dir") if pub.get("pages_dir") not in (None, "") else "docs")
    if not PAGES_DIR.match(pages_dir_name):
        return fail(f"publish.pages_dir '{pages_dir_name}' is not allowed: one folder name of letters, digits, - or _ (up to 40),"
                    " such as 'docs'")
    brief = args.brief or (root / str(((m.get("source") or {}).get("ingested")) or "work/brief.json"))
    brief = brief.resolve()
    if not brief.is_file():
        return fail(f"no brief at {brief}")

    portals = {"user": pub.get("user_portal") or {}, "admin": pub.get("admin_portal") or {}}
    for p in ("user", "admin"):
        cur = str(portals[p].get("path") or "")
        if cur and not HEXPATH.match(cur):
            return fail(f"publish.{p}_portal.path '{cur}' is not allowed: lowercase hex, at least 8 characters; leave it empty"
                        " to have one generated")
    if portals["user"].get("path") and portals["user"].get("path") == portals["admin"].get("path"):
        return fail("publish.user_portal.path and publish.admin_portal.path are the same; give each its own (or leave one empty)")
    locks = {"user": bool(portals["user"].get("lock")), "admin": bool(portals["admin"].get("lock", True))}
    if not locks["admin"]:
        print("[publish] warning: the admin portal is not locked; anyone with the link sees the team's admin section")

    gh_ok = False
    if args.run_gh and host == "github-pages":
        if not interactive():
            print("[publish] refusing --run-gh: there is no interactive terminal to confirm in (an agent or a script cannot"
                  " create a public repository with the person's GitHub account). The commands are printed at the end instead.")
        else:
            gh_ok = True

    base = args.out_dir.resolve() if args.out_dir else None
    out_dir = base if base else root / "output"
    publish_root = ((base or root) / pages_dir_name) if host == "github-pages" else ((base or root) / "dist")

    pass_dir = None
    if any(locks.values()):
        if not pub.get("passphrases_dir"):
            return fail("publish.passphrases_dir is required when a portal is locked (a folder outside the repo)")
        pass_dir = Path(str(pub["passphrases_dir"]))
        if not pass_dir.is_absolute():
            pass_dir = (mpath.parent / pass_dir)
        pass_dir = pass_dir.resolve()
        print(f"[publish] passphrase folder: {pass_dir} (a relative passphrases_dir is taken from the manifest's folder,"
              f" {mpath.parent})")
        if inside(pass_dir, publish_root) or inside(pass_dir, out_dir):
            return fail("publish.passphrases_dir is inside a folder that gets published or built; move it outside")
        if inside(pass_dir, root) and "projects" not in pass_dir.relative_to(root).parts:
            print("[publish] warning: passphrases_dir is inside the kit folder and not under the gitignored projects/; make sure it is never committed")
        for p in ("user", "admin"):
            if locks[p] and portals[p].get("published") and not (pass_dir / f"{p}.txt").is_file():
                return fail(f"STOPPED: the {p} portal was published before (publish.{p}_portal.published is true) but its"
                            f" passphrase file is not at {pass_dir / (p + '.txt')}. Nothing was built. If the folder is wrong,"
                            f" fix publish.passphrases_dir (relative to {mpath.parent}). If you mean to issue a new passphrase"
                            f" to that group, set publish.{p}_portal.published to false and re-run, then tell the group.")

    # random paths, written back before locking (lock.py rewrites the manifest too, so it must read the current one)
    changed = False
    for p in ("user", "admin"):
        if not portals[p].get("path"):
            new = secrets.token_hex(8)
            while new == portals["user" if p == "admin" else "admin"].get("path"):
                new = secrets.token_hex(8)
            portals[p]["path"] = new
            changed = True
    if changed:
        pub["user_portal"], pub["admin_portal"] = portals["user"], portals["admin"]
        mpath.write_text(json.dumps(m, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print("[publish] wrote the portal paths into the manifest")

    py = sys.executable
    plain = {"user": out_dir / "index.html", "admin": out_dir / "admin" / "index.html"}
    chat_mode = (m.get("chat") or {}).get("mode")
    for p in ("user", "admin"):
        cmd = [py, "-X", "utf8", str(CHAIN), "--brief", str(brief), "--manifest", str(mpath), "--root", str(root),
               "--out", str(plain[p]), "--portal", p]
        if p == "user" and chat_mode == "direct":
            cmd += ["--skip", "ek-chat"]   # direct mode is admin-only: a visitor has no key
        code, txt = run(cmd)
        for line in txt.splitlines():
            print(f"   {line}")
        if code != 0:
            return fail(f"{p} portal build failed (exit {code})")
        print(f"[publish] {p} portal built: {plain[p]}")

    titles = {"user": str(portals["user"].get("title") or "Engagement tool")[:80],
              "admin": str(portals["admin"].get("title") or "Design team portal")[:80]}
    for p in ("user", "admin"):
        rel = Path("p") / portals[p]["path"] if host == "github-pages" else Path(portals[p]["path"])
        dest = publish_root / rel / "index.html"
        dest.parent.mkdir(parents=True, exist_ok=True)
        if locks[p]:
            code, txt = run([py, "-X", "utf8", str(LOCK), "--in", str(plain[p]), "--out", str(dest),
                             "--passphrase-file", str(pass_dir / f"{p}.txt"), "--manifest", str(mpath), "--title", titles[p]])
            if code != 0:
                return fail(f"locking the {p} portal failed: {txt[-400:]}")
            try:
                info = json.loads(txt[txt.index("{"):])
                how = info.get("passphrase", "").split(" ")[0]
            except Exception:
                how = "?"
            if how == "generated":
                print(f"[publish] NEW PASSPHRASE generated into {pass_dir / (p + '.txt')} for the {p} portal (not shown);"
                      " hand it out as the README says")
            print(f"[publish] {p} portal locked → {dest} (passphrase {how} {p}.txt; not shown)")
        else:
            shutil.copyfile(plain[p], dest)
            print(f"[publish] {p} portal public → {dest}")

    if host == "github-pages":
        repo = pub["repo"]
        links = {p: pages_url(repo, portals[p]["path"]) for p in ("user", "admin")}
        route = beginner_route(repo, pages_dir_name, links, publish_root)
        gh_lines = gh_commands(repo, pages_dir_name)
        upload = None
    else:
        dom = str(pub["domain"]).rstrip("/")
        links = {p: f"{dom}/{portals[p]['path']}/" for p in ("user", "admin")}
        route, gh_lines, upload = [], [], str(publish_root)

    rebuild = (f"python -X utf8 skills/ek-publish/publish.py --manifest \"{mpath}\" --brief \"{brief}\""
               + (f" --out-dir \"{base}\"" if base else ""))
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "README.md").write_text(private_readme(m, pub, links, locks, pass_dir, rebuild, route, gh_lines, upload),
                                       encoding="utf-8", newline="\n")
    print(f"[publish] private README → {out_dir / 'README.md'} (never publish this file)")
    pub_readme = publish_root / "README.md"
    if pub.get("public_readme") is True:
        pub_readme.write_text(public_readme(titles["user"], links["user"], locks["user"]), encoding="utf-8", newline="\n")
        print(f"[publish] public README (title and user link only) → {pub_readme}")
    elif pub_readme.is_file() and "built with Engage Kit" in pub_readme.read_text(encoding="utf-8", errors="replace"):
        pub_readme.unlink()
        print(f"[publish] removed an older public README from {publish_root} (it named the project); upload the folder again")

    # record the publish (lock.py may have rewritten the manifest: re-read it)
    m2 = json.loads(mpath.read_text(encoding="utf-8-sig"))
    today = datetime.date.today().isoformat()
    for p in ("user", "admin"):
        blk = m2.setdefault("publish", {}).setdefault(f"{p}_portal", {})
        blk["published"] = True
        blk["published_on"] = today
    mpath.write_text(json.dumps(m2, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    print(f"[publish] user portal:  {links['user']}")
    print(f"[publish] admin portal: {links['admin']}")
